// Writes worker/assets.generated.ts: every file in dist/ inlined as a string,
// so the site ships as one Worker script. Run after `vite build`.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
const out = join(root, 'worker', 'assets.generated.ts');

const TEXT = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
};
const BINARY = {
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const assets = {};
if (existsSync(dist)) {
  for (const path of walk(dist)) {
    const ext = extname(path).toLowerCase();
    const url = '/' + relative(dist, path).split(sep).join('/');
    if (TEXT[ext]) assets[url] = { type: TEXT[ext], body: readFileSync(path, 'utf8') };
    else if (BINARY[ext]) assets[url] = { type: BINARY[ext], body: readFileSync(path).toString('base64'), base64: true };
    else throw new Error(`No content type known for ${url}; add it to scripts/gen-assets.mjs`);
  }
}

writeFileSync(
  out,
  '// Generated by scripts/gen-assets.mjs. Do not edit.\n' +
    'export interface Asset {\n  type: string;\n  body: string;\n  base64?: boolean;\n}\n\n' +
    `export const ASSETS: Record<string, Asset> = ${JSON.stringify(assets)};\n`,
);
const bytes = Object.values(assets).reduce((n, a) => n + a.body.length, 0);
console.log(`gen-assets: ${Object.keys(assets).length} files, ${(bytes / 1024).toFixed(0)} KiB`);
